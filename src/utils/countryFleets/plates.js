function detectIndianState(lat, lon) {
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return null;

  // Gujarat
  if (lat >= 20.0 && lat <= 24.7 && lon >= 68.1 && lon <= 74.5) return 'GJ';
  // Maharashtra
  if (lat >= 15.6 && lat <= 22.1 && lon >= 72.6 && lon <= 80.9) return 'MH';
  // Delhi NCR
  if (lat >= 28.3 && lat <= 28.9 && lon >= 76.8 && lon <= 77.4) return 'DL';
  // Karnataka
  if (lat >= 11.5 && lat <= 18.5 && lon >= 74.0 && lon <= 78.6) return 'KA';
  // Tamil Nadu
  if (lat >= 8.0 && lat <= 13.5 && lon >= 76.2 && lon <= 80.4) return 'TN';
  // Telangana
  if (lat >= 15.8 && lat <= 19.9 && lon >= 77.2 && lon <= 81.8) return 'TS';
  // Uttar Pradesh
  if (lat >= 23.8 && lat <= 30.4 && lon >= 77.0 && lon <= 84.6) return 'UP';
  // West Bengal
  if (lat >= 21.5 && lat <= 27.2 && lon >= 85.8 && lon <= 89.9) return 'WB';
  // Rajasthan
  if (lat >= 23.0 && lat <= 30.2 && lon >= 69.5 && lon <= 78.3) return 'RJ';
  // Kerala
  if (lat >= 8.2 && lat <= 12.8 && lon >= 74.8 && lon <= 77.4) return 'KL';
  // Haryana
  if (lat >= 27.6 && lat <= 30.9 && lon >= 74.5 && lon <= 77.6) return 'HR';
  // Punjab
  if (lat >= 29.5 && lat <= 32.5 && lon >= 73.8 && lon <= 76.9) return 'PB';
  // Madhya Pradesh
  if (lat >= 21.3 && lat <= 26.9 && lon >= 74.0 && lon <= 82.8) return 'MP';
  // Andhra Pradesh
  if (lat >= 12.6 && lat <= 19.1 && lon >= 76.7 && lon <= 84.8) return 'AP';
  // Goa
  if (lat >= 14.8 && lat <= 15.8 && lon >= 73.6 && lon <= 74.4) return 'GA';

  return null;
}

const SERIES_LETTERS = [
  'AB', 'CD', 'EF', 'GH', 'JK', 'MN', 'PQ', 'RS', 'EV', 'AX',
  'BZ', 'DN', 'EK', 'FD', 'CB', 'ZT', 'WA', 'BB', 'CC', 'DD',
  'AA', 'AZ', 'BY', 'CX', 'DW', 'EV', 'FU', 'GT', 'HS', 'JR',
];

export function generateRegionalPlate(countryCode, seed, options = {}) {
  const pseudo = (Math.abs(Math.sin(seed * 12.9898 + 78.233)) % 1);
  const lat = options.lat !== undefined ? Number(options.lat) : null;
  const lon = options.lon !== undefined ? Number(options.lon) : null;

  // --- INDIA (IN) ---
  if (countryCode === 'IN') {
    // 1. Detect state if geodetic coordinates are available, otherwise pick authentically
    const detectedState = detectIndianState(lat, lon);
    const stateKeys = Object.keys(INDIAN_RTO_REGISTRY);
    const state = detectedState || stateKeys[Math.floor(pseudo * stateKeys.length)];
    const rtoList = INDIAN_RTO_REGISTRY[state] || INDIAN_RTO_REGISTRY.GJ;

    // Pick authentic RTO code for this state
    const rtoIndex = Math.floor((pseudo * 31 + seed * 13) % rtoList.length);
    const rtoEntry = rtoList[rtoIndex];
    const rtoCode = rtoEntry.code;

    // 2. Realistic Series (1 or 2 letters)
    const seriesIndex = Math.floor((pseudo * 19 + seed * 7) % SERIES_LETTERS.length);
    const series = SERIES_LETTERS[seriesIndex];

    // 3. Random 4 digits (0001 to 9999, padded to 4 digits)
    const rawNum = Math.floor(1 + ((seed * 37 + pseudo * 9973) % 9999));
    const num = String(rawNum).padStart(4, '0');

    return `${rtoCode} ${series} ${num}`;
  }

  // --- UNITED STATES (US) ---
  if (countryCode === 'US') {
    const states = ['CA', 'NY', 'TX', 'FL', 'WA', 'IL', 'CO', 'GA', 'MI', 'AZ'];
    const state = states[Math.floor(pseudo * states.length)];
    const letters = ['ABC', 'DFW', 'HLM', 'KVP', 'SEA', 'MIA', 'DEN', 'ORD'][Math.floor(((seed * 3) % 8))];
    const num = String(Math.floor(1000 + ((seed * 41) % 8999)));
    if (state === 'CA') {
      const d1 = Math.floor(7 + ((seed * 3) % 3));
      return `${d1}${letters}${num.slice(-3)}`;
    }
    return `${state} · ${letters}-${num}`;
  }

  // --- UNITED KINGDOM (GB) ---
  if (countryCode === 'GB') {
    const prefixes = ['LD', 'LJ', 'BD', 'WN', 'KV', 'MD', 'SK', 'OV', 'EA'];
    const prefix = prefixes[Math.floor(pseudo * prefixes.length)];
    const year = ['21', '22', '23', '24', '72', '73', '74'][Math.floor(((seed * 3) % 7))];
    const suffixes = ['WKY', 'XLP', 'ZTY', 'JHN', 'KVM', 'PXL', 'BTH'];
    const suffix = suffixes[Math.floor(((seed * 5) % suffixes.length))];
    return `${prefix}${year} ${suffix}`;
  }

  // --- GERMANY (DE) ---
  if (countryCode === 'DE') {
    const cities = ['B', 'M', 'S', 'HH', 'F', 'K', 'N', 'D'];
    const city = cities[Math.floor(pseudo * cities.length)];
    const letters = ['MW', 'TS', 'GT', 'KL', 'XY', 'EV', 'RS'][Math.floor(((seed * 5) % 7))];
    const num = Math.floor(1000 + ((seed * 19) % 8999));
    return `${city}-${letters} ${num}`;
  }

  // --- JAPAN (JP) ---
  if (countryCode === 'JP') {
    const prefs = ['品川', '練馬', '横浜', 'なにわ', '名古屋', '福岡', '札幌'];
    const pref = prefs[Math.floor(pseudo * prefs.length)];
    const hira = ['さ', 'た', 'な', 'ほ', 'と'][Math.floor(((seed * 3) % 5))];
    const n1 = String(Math.floor(10 + ((seed * 17) % 89)));
    const n2 = String(Math.floor(10 + ((seed * 23) % 89)));
    return `${pref} 330 ${hira} ${n1}-${n2}`;
  }

  // --- CHINA (CN) ---
  if (countryCode === 'CN') {
    const provs = ['京A', '沪A', '粤B', '浙A', '苏A', '川A', '鲁A', '鄂A'];
    const prov = provs[Math.floor(pseudo * provs.length)];
    const num = Math.floor(10000 + ((seed * 37) % 89999));
    return `${prov}·${num}`;
  }

  // --- SOUTH KOREA (KR) ---
  if (countryCode === 'KR') {
    const prefix = Math.floor(100 + ((seed * 19) % 899));
    const hangeul = ['가', '나', '다', '라', '마', '바', '사', '아', '자', '차'][Math.floor(((seed * 7) % 10))];
    const num = Math.floor(1000 + ((seed * 31) % 8999));
    return `${prefix}${hangeul} ${num}`;
  }

  // --- FRANCE (FR) ---
  if (countryCode === 'FR') {
    const l1 = ['AB', 'CD', 'EF', 'GH', 'JK', 'FR'][Math.floor(pseudo * 6)];
    const num = String(Math.floor(100 + ((seed * 13) % 899))).padStart(3, '0');
    const l2 = ['XY', 'WZ', 'TR', 'QS', 'XP'][Math.floor(((seed * 7) % 5))];
    return `${l1}-${num}-${l2}`;
  }

  // --- AUSTRALIA (AU) ---
  if (countryCode === 'AU') {
    const states = ['NSW', 'VIC', 'QLD', 'WA', 'SA'];
    const state = states[Math.floor(pseudo * states.length)];
    const letters = ['ABC', 'XYZ', 'EVT', 'NEX'][Math.floor(((seed * 3) % 4))];
    const num = Math.floor(100 + ((seed * 17) % 899));
    return `${state} · ${letters}-${num}`;
  }

  // --- CANADA (CA) ---
  if (countryCode === 'CA') {
    const provs = ['ON', 'QC', 'BC', 'AB', 'MB'];
    const prov = provs[Math.floor(pseudo * provs.length)];
    const num = Math.floor(100 + ((seed * 23) % 899));
    return `${prov} · ABCD ${num}`;
  }

  // --- BRAZIL (BR) ---
  if (countryCode === 'BR') {
    const num = Math.floor(1 + ((seed * 7) % 9));
    const end = Math.floor(10 + ((seed * 17) % 89));
    return `BRA${num}D${end}`;
  }

  // --- SPAIN (ES) ---
  if (countryCode === 'ES') {
    const num = String(Math.floor(1000 + ((seed * 23) % 8999)));
    const letters = ['BCD', 'FGH', 'JKL', 'MNP', 'RST'][Math.floor(pseudo * 5)];
    return `${num} ${letters}`;
  }

  // --- ITALY (IT) ---
  if (countryCode === 'IT') {
    const l1 = ['GA', 'GE', 'GF', 'GG', 'GH'][Math.floor(pseudo * 5)];
    const num = String(Math.floor(100 + ((seed * 17) % 899))).padStart(3, '0');
    const l2 = ['AA', 'BB', 'CC', 'DD'][Math.floor(((seed * 3) % 4))];
    return `${l1} ${num} ${l2}`;
  }

  // --- UAE (AE) ---
  if (countryCode === 'AE') {
    const emirates = ['DXB', 'AUH', 'SHJ'];
    const em = emirates[Math.floor(pseudo * emirates.length)];
    const code = ['A', 'B', 'C', 'D', 'E', 'F'][Math.floor(((seed * 5) % 6))];
    const num = Math.floor(1000 + ((seed * 31) % 8999));
    return `${em} · ${code} ${num}`;
  }

  // Global default
  const num = Math.floor(1000 + ((seed * 29) % 8999));
  return `INT · ${num}`;
}
